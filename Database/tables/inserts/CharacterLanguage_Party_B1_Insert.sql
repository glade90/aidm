USE [DnD];
GO
SET XACT_ABORT ON;
GO

IF OBJECT_ID(N'characters.CharacterLanguage', N'U') IS NULL
    THROW 55200, 'Missing characters.CharacterLanguage. Run CharacterLanguage.sql first.', 1;
IF OBJECT_ID(N'Rules.Languages', N'U') IS NULL
    THROW 55201, 'Missing Rules.Languages. Run Languages.sql and its seed first.', 1;
IF OBJECT_ID(N'characters.Character', N'U') IS NULL
    THROW 55202, 'Missing characters.Character. Insert character identities first.', 1;
GO

DECLARE @Assignments TABLE
(
    CharacterName NVARCHAR(60) NOT NULL,
    ExpectedAlignment NVARCHAR(20) NOT NULL,
    LanguageCode NVARCHAR(50) NOT NULL,
    AcquisitionMethod NVARCHAR(30) NOT NULL,
    CanSpeak BIT NOT NULL,
    CanRead BIT NOT NULL,
    CanWrite BIT NOT NULL,
    NotesMarkdown NVARCHAR(MAX) NULL,
    PRIMARY KEY (CharacterName, LanguageCode)
);

INSERT INTO @Assignments
    (CharacterName, ExpectedAlignment, LanguageCode,
     AcquisitionMethod, CanSpeak, CanRead, CanWrite, NotesMarkdown)
VALUES
    (N'Ralt', N'Chaotic', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'Automatic Common tongue. Intelligence 18 grants normal literacy.'),
    (N'Ralt', N'Chaotic', N'ALIGN_CHAOTIC', N'StartingAlignment', 1, 0, 0,
     N'Secret Chaotic alignment tongue. Passwords, signs and gestures; never written. Automatically replaced on alignment change.'),
    (N'Ralt', N'Chaotic', N'ORC', N'IntelligenceBonus', 1, 1, 1,
     N'Chosen explicitly by the player as the first of Ralt''s three additional languages from INT 18.'),
    (N'Ralt', N'Chaotic', N'HARPY', N'IntelligenceBonus', 1, 1, 1,
     N'Player-rolled additional language: result 11 in the numbered DM language list. Uses player-approved hybrid random method.'),
    (N'Ralt', N'Chaotic', N'HOBGOBLIN', N'IntelligenceBonus', 1, 1, 1,
     N'Player-rolled additional language: result 12 in the numbered DM language list. Uses player-approved hybrid random method.'),
    (N'Wilberd', N'Neutral', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'INT 8: Common spoken and readable; writing is limited to simple words under the Basic Intelligence language table. CanWrite=1 alone does not convey this restriction.'),
    (N'Wilberd', N'Neutral', N'ALIGN_NEUTRAL', N'StartingAlignment', 1, 0, 0,
     N'Unwritten Neutral alignment tongue; replaced automatically on an alignment change.'),
    (N'Sho-Rembo', N'Neutral', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'Automatic Common language; ordinary literacy (INT 11). No extra racial tongue is assumed without a specific rule or decision.'),
    (N'Sho-Rembo', N'Neutral', N'ALIGN_NEUTRAL', N'StartingAlignment', 1, 0, 0,
     N'Unwritten Neutral alignment tongue; replaced automatically on an alignment change.'),
    (N'Pell', N'Neutral', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'Automatic Common language; ordinary literacy (INT 10).'),
    (N'Pell', N'Neutral', N'ALIGN_NEUTRAL', N'StartingAlignment', 1, 0, 0,
     N'Unwritten Neutral alignment tongue; replaced automatically on an alignment change.'),
    (N'Alho', N'Lawful', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'Automatic Common language; ordinary literacy (INT 10).'),
    (N'Alho', N'Lawful', N'ALIGN_LAWFUL', N'StartingAlignment', 1, 0, 0,
     N'Unwritten Lawful alignment tongue; replaced automatically on an alignment change.'),
    (N'Evro', N'Neutral', N'COMMON', N'StartingCommon', 1, 1, 1,
     N'Automatic Common language; ordinary literacy (INT 9).'),
    (N'Evro', N'Neutral', N'ALIGN_NEUTRAL', N'StartingAlignment', 1, 0, 0,
     N'Unwritten Neutral alignment tongue; replaced automatically on an alignment change.');

BEGIN TRY
    BEGIN TRANSACTION;

    -- Require an active character identity with its approved alignment.
    IF EXISTS
    (
        SELECT 1 FROM @Assignments AS a
        WHERE NOT EXISTS
        (
            SELECT 1 FROM [characters].[Character] AS c
            WHERE c.CharacterName = a.CharacterName
              AND c.Active = 1
              AND c.InitialAlignment = a.ExpectedAlignment
        )
    )
        THROW 55203, 'An active character is missing or has a different starting alignment. Verify character inserts first.', 1;

    -- Guard Ralt's already approved INT 18 entitlement.
    IF NOT EXISTS
    (
        SELECT 1 FROM [characters].[Character]
        WHERE CharacterName = N'Ralt' AND Active = 1
          AND InitialClass = N'Magic-User' AND Intelligence = 18
    )
        THROW 55204, 'Ralt active identity or Intelligence 18 does not match locked character.', 1;

    -- Require an active language catalog entry for each approved language.
    IF EXISTS
    (
        SELECT 1 FROM @Assignments AS a
        WHERE NOT EXISTS
        (
            SELECT 1 FROM [Rules].[Languages] AS l
            WHERE l.RulesetCode = N'MentzerBECMI'
              AND l.LanguageCode = a.LanguageCode
              AND l.Active = 1
              AND l.LanguageKind <> N'Placeholder'
        )
    )
        THROW 55205, 'An approved language is missing from active Rules.Languages.', 1;

    -- Alignment-language rows must match the character alignment; no mixing.
    IF EXISTS
    (
        SELECT 1
        FROM [characters].[CharacterLanguage] AS cl
        JOIN @Assignments AS a ON a.CharacterName = cl.CharacterName
        WHERE cl.RulesetCode = N'MentzerBECMI' AND cl.Active = 1
          AND cl.LanguageCode IN (N'ALIGN_LAWFUL', N'ALIGN_NEUTRAL', N'ALIGN_CHAOTIC')
          AND cl.LanguageCode <> CONCAT(N'ALIGN_', UPPER(a.ExpectedAlignment))
    )
        THROW 55206, 'A character has an active alignment tongue inconsistent with approved alignment. Review manually.', 1;

    -- An active assignment with conflicting meaning is never silently overwritten.
    IF EXISTS
    (
        SELECT 1
        FROM @Assignments AS a
        JOIN [characters].[CharacterLanguage] AS cl
          ON cl.CharacterName = a.CharacterName
         AND cl.RulesetCode = N'MentzerBECMI'
         AND cl.LanguageCode = a.LanguageCode
         AND cl.Active = 1
        WHERE cl.AcquisitionMethod <> a.AcquisitionMethod
           OR cl.CanSpeak <> a.CanSpeak
           OR ISNULL(CONVERT(INT, cl.CanRead), -1) <> CONVERT(INT, a.CanRead)
           OR ISNULL(CONVERT(INT, cl.CanWrite), -1) <> CONVERT(INT, a.CanWrite)
    )
        THROW 55207, 'An existing active language assignment conflicts with the approved values. No overwrite.', 1;

    -- Cannot insert a second version with a DATE-based PK on the same day.
    IF EXISTS
    (
        SELECT 1 FROM @Assignments AS a
        JOIN [characters].[CharacterLanguage] AS cl
          ON cl.CharacterName = a.CharacterName
         AND cl.RulesetCode = N'MentzerBECMI'
         AND cl.LanguageCode = a.LanguageCode
         AND cl.RecordDate = CONVERT(DATE, SYSUTCDATETIME())
         AND cl.Active = 0
        WHERE NOT EXISTS
        (
            SELECT 1 FROM [characters].[CharacterLanguage] AS cl2
            WHERE cl2.CharacterName = a.CharacterName
              AND cl2.RulesetCode = N'MentzerBECMI'
              AND cl2.LanguageCode = a.LanguageCode
              AND cl2.Active = 1
        )
    )
        THROW 55208, 'An inactive language version already exists today. DATE key prevents another same-day version.', 1;

    INSERT INTO [characters].[CharacterLanguage]
    (
        [CharacterName], [RulesetCode], [LanguageCode], [Active],
        [CharacterRecordDate], [LanguageRecordDate],
        [AcquisitionMethod], [LearnedOn],
        [CanSpeak], [CanRead], [CanWrite], [NotesMarkdown]
    )
    SELECT a.CharacterName, N'MentzerBECMI', a.LanguageCode, 1,
           c.RecordDate, l.RecordDate,
           a.AcquisitionMethod, NULL,
           a.CanSpeak, a.CanRead, a.CanWrite, a.NotesMarkdown
    FROM @Assignments AS a
    JOIN [characters].[Character] AS c
      ON c.CharacterName = a.CharacterName AND c.Active = 1
    JOIN [Rules].[Languages] AS l
      ON l.RulesetCode = N'MentzerBECMI'
     AND l.LanguageCode = a.LanguageCode AND l.Active = 1
    WHERE NOT EXISTS
    (
        SELECT 1 FROM [characters].[CharacterLanguage] AS prior
        WHERE prior.CharacterName = a.CharacterName
          AND prior.RulesetCode = N'MentzerBECMI'
          AND prior.LanguageCode = a.LanguageCode
          AND prior.Active = 1
    );

    PRINT CONCAT(N'New character-language assignments inserted: ', @@ROWCOUNT);
    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO

-- Read-only verification. Expect 15 active assignments across 6 characters.
SELECT
    cl.CharacterName,
    l.LanguageName,
    l.LanguageKind,
    cl.AcquisitionMethod,
    cl.CanSpeak,
    cl.CanRead,
    cl.CanWrite,
    cl.NotesMarkdown
FROM [characters].[CharacterLanguage] AS cl
JOIN [Rules].[Languages] AS l
  ON l.RecordDate = cl.LanguageRecordDate
 AND l.RulesetCode = cl.RulesetCode
 AND l.LanguageCode = cl.LanguageCode
WHERE cl.RulesetCode = N'MentzerBECMI' AND cl.Active = 1
  AND cl.CharacterName IN (N'Ralt', N'Wilberd', N'Sho-Rembo', N'Pell', N'Alho', N'Evro')
ORDER BY cl.CharacterName,
         CASE WHEN cl.AcquisitionMethod = N'StartingCommon' THEN 0
              WHEN cl.AcquisitionMethod = N'StartingAlignment' THEN 1
              ELSE 2 END,
         l.LanguageName;
GO
