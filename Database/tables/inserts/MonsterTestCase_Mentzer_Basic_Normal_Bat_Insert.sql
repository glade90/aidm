 INSERT INTO [Test].[MonsterTestCase]
 (
    [ScenarioCode],
    [TestCaseCode],
    [SequenceNo],
    [TestName],
    [TestPhase],
    [TestStatus],
    [TestRevision],
    [GivenText],
    [ExpectedText],
    [DiceFixtureJson],
    [AdditionalDataJson],
    [LinkedStoryRef],
    [AutomatedTestRef],
    [Notes]
 )
 SELECT
    s.[ScenarioCode],
    s.[TestCaseCode],
    s.[SequenceNo],
    s.[TestName],
    s.[TestPhase],
    s.[TestStatus],
    s.[TestRevision],
    s.[GivenText],
    s.[ExpectedText],
    s.[DiceFixtureJson],
    s.[AdditionalDataJson],
    s.[LinkedStoryRef],
    s.[AutomatedTestRef],
    s.[Notes]
 FROM @Seed s
 WHERE NOT EXISTS
 (SELECT 1 FROM [Test].[MonsterTestCase] AS e WITH(UPDLOCK,HOLDLOCK)
  WHERE e.[ScenarioCode]=s.[ScenarioCode]
    AND e.[TestCaseCode]=s.[TestCaseCode]);
 PRINT CONCAT(N'Inserted Normal Bat test cases: ',@@ROWCOUNT);
 COMMIT;
END TRY
BEGIN CATCH
 IF @@TRANCOUNT>0 ROLLBACK;
 THROW;
END CATCH;
GO
